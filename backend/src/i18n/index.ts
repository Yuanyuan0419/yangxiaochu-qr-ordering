const DICTS: Record<Lang, Messages> = { zh, en, fr };

/**
 * Translates a message key. Keys may carry one inline param as "key|value" (used by Zod messages, e.g. "v.tooLong|120").
 * Unknown keys are returned unchanged.
 */
export function t(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const [k, inline] = key.split("|");
  const template = DICTS[lang][k] ?? DICTS.zh[k];
  if (!template) return key;
  const all = inline !== undefined ? { max: inline, ...params } : params;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(all[name] ?? ""));
}
