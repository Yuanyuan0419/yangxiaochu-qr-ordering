import type { Request } from "express";

export const LANGS = ["zh", "en", "fr"] as const;
export type Lang = (typeof LANGS)[number];

/** Picks the first supported language from Accept-Language (the frontend sends the user's chosen UI language). */
export function langOf(req: Request): Lang {
  const header = req.headers["accept-language"] ?? "";
  for (const part of header.split(",")) {
    const code = part.trim().slice(0, 2).toLowerCase();
    if ((LANGS as readonly string[]).includes(code)) return code as Lang;
  }
  return "zh";
}

